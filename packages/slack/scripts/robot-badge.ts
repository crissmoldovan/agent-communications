/**
 * Draws the robot badge `icon make` puts on a person's photo, and writes it into the package as a PNG.
 *
 *   node --experimental-strip-types packages/slack/scripts/robot-badge.ts
 *
 * The badge is drawn here, from the pixel map below, and from nothing else: an original picture made for this
 * package — a round blue badge with a white rim and a robot's head on it — not copied from anywhere. The map is 16 by
 * 16; each of its pixels is drawn as a 3 × 3 block, so the badge is 48 pixels square: a little over a third of the
 * 128-pixel emoji, enough to read as a robot at the size Slack shows an emoji, and small enough that the photo is still
 * the picture.
 *
 * The PNG it writes, `src/icon/robot-badge.ts`, is embedded in source rather than kept as a file beside it, so the
 * bundle carries it with the code that reads it — there is no asset to forget to copy, and no path to resolve at run
 * time. `test/agent-label-icon.test.ts` decodes the embedded PNG and fails unless it is exactly what this draws: change
 * the map, then run this again.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PNG } from 'pngjs';

/**
 * The badge, a character a pixel: `.` clear, `o` the white rim, `b` the blue of the badge, `w` the robot, `k` its eyes
 * and mouth, `a` the light on its antenna.
 */
export const BADGE_MAP: readonly string[] = [
  '.....oooooo.....',
  '...oobbbbbboo...',
  '..obbbbaabbbbo..',
  '.obbbbbwwbbbbbo.',
  '.obbbwwwwwwbbbo.',
  'obbbwwwwwwwwbbbo',
  'obbbwkkwwkkwbbbo',
  'obbwwkkwwkkwwbbo',
  'obbwwwwwwwwwwbbo',
  'obbbwwkkkkwwbbbo',
  'obbbbwwwwwwbbbbo',
  '.obbbbbbbbbbbbo.',
  '.obbbbbbbbbbbbo.',
  '..obbbbbbbbbbo..',
  '...oobbbbbboo...',
  '.....oooooo.....',
];

/** Each character's colour, as RGBA. */
export const BADGE_COLOURS: Readonly<Record<string, readonly [number, number, number, number]>> = {
  '.': [0, 0, 0, 0],
  o: [255, 255, 255, 255],
  b: [37, 99, 235, 255],
  w: [241, 245, 249, 255],
  k: [15, 23, 42, 255],
  a: [245, 158, 11, 255],
};

/** How many pixels of the badge each character of the map is, across and down. */
export const BADGE_SCALE = 3;

/** The badge as RGBA pixels, `BADGE_SCALE` times the map. */
export function drawRobotBadge(): { width: number; height: number; data: Uint8Array } {
  const rows = BADGE_MAP.length;
  const columns = BADGE_MAP[0]?.length ?? 0;
  if (rows === 0 || BADGE_MAP.some((row) => row.length !== columns)) {
    throw new Error('every row of the badge map is as long as the first');
  }
  const width = columns * BADGE_SCALE;
  const height = rows * BADGE_SCALE;
  const data = new Uint8Array(width * height * 4);
  for (let y = 0; y < height; y += 1) {
    const row = BADGE_MAP[Math.floor(y / BADGE_SCALE)] ?? '';
    for (let x = 0; x < width; x += 1) {
      const key = row[Math.floor(x / BADGE_SCALE)] ?? '.';
      const colour = BADGE_COLOURS[key];
      if (colour === undefined) throw new Error(`the badge map has a character with no colour: ${key}`);
      data.set(colour, (y * width + x) * 4);
    }
  }
  return { width, height, data };
}

/** The badge as PNG bytes. */
export function robotBadgePng(): Buffer {
  const badge = drawRobotBadge();
  const png = new PNG({ width: badge.width, height: badge.height });
  png.data = Buffer.from(badge.data);
  return PNG.sync.write(png, { colorType: 6, deflateLevel: 9 });
}

/** The module `src/icon/robot-badge.ts`, holding the PNG. */
export function robotBadgeModule(): string {
  const base64 = robotBadgePng().toString('base64');
  const lines = base64.match(/.{1,100}/g) ?? [];
  return [
    '// Generated by scripts/robot-badge.ts from its pixel map. Do not edit: change the map and run the script again.',
    '',
    '/**',
    ' * The robot badge `icon make` draws on the lower right of a person’s photo: a 48-pixel PNG, drawn for this package',
    ' * and embedded here so the bundle carries it with the code that reads it.',
    ' */',
    'export const ROBOT_BADGE_PNG: Buffer = Buffer.from(',
    '  [',
    ...lines.map((line) => `    '${line}',`),
    "  ].join(''),",
    "  'base64',",
    ');',
    '',
  ].join('\n');
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  const target = fileURLToPath(new URL('../src/icon/robot-badge.ts', import.meta.url));
  writeFileSync(target, robotBadgeModule());
  process.stdout.write(`wrote ${target}\n`);
}
