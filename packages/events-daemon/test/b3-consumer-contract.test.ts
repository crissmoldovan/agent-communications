/** Keep checked-in JSON Biome-formatted while preserving byte-for-byte regeneration from data-only values. */
function vectorJson(value: unknown): string {
  return `${JSON.stringify(value, null, 2).replace(
    /\[\n\s+((?:true|false|null|-?\d+(?:\.\d+)?|"(?:[^"\\]|\\.)*"))\n\s*\]/gu,
    '[$1]',
  )}\n`;
}

async function vectors(): Promise<ReadonlyMap<string, Readonly<Record<string, unknown>>>> {
  const files = (await readdir(FIXTURES)).filter((name) => name.endsWith('.json')).sort();
  const raw = await Promise.all(
    files.map(
      async (name) => JSON.parse(await readFile(join(FIXTURES, name), 'utf8')) as Readonly<Record<string, unknown>>,
    ),
  );
  const values = raw.flatMap((value) => (Array.isArray(value) ? value : [value])) as Readonly<
    Record<string, unknown>
  >[];
  return new Map(values.map((value) => [value.name as string, value]));
}

test('B3 data-only consumer vectors drive real owner results and retain the C/E boundary', {
  skip: WINDOWS_SKIP,
}, async () => {
  const fixture = await vectors();
  const stateDir = await shortTempDir('aev-b3-consumer-contract-');
  const store = await openEventDatabase({ stateDir });
  let secretCalls = 0;
  let approvalChallenge: string | null = 'challenge-1';
  try {
    const vector = (name: string) => {
      const value = fixture.get(name);
      assert.ok(value, `the ${name} consumer vector is checked in`);
      return value;
    };
    const request = (name: string) => vector(name).request as { operation: string; args: Record<string, unknown> };
    const assertVectorFile = async (file: string, value: Readonly<Record<string, unknown>>) => {
      assert.equal(
        await readFile(join(FIXTURES, file), 'utf8'),
        vectorJson(value),
        `${file} is regenerated byte-for-byte from its real owner operation`,
      );
    };
    const doctor = await projectB3Doctor({
      database: store.database,
      installationId: 'installation-1',
      lifecycle: { enabled: true, paused: false, switchGeneration: 1 },
      protocolVersions: [1],
      ports: { assertObjectSecretReady: async () => undefined } as never,
      config: { load: async () => ({ inboxes: {}, accounts: {} }) } as never,
      approvals: { get: async () => null } as never,
      decryptSourceState: async () => null,
      now: () => 1_000,
    });
    assert.deepEqual(
      doctor,
      vector('doctor-result').result,
      'the checked-in doctor result comes from its real projection',
    );
    assert.equal(
      await readFile(join(FIXTURES, 'doctor-result.json'), 'utf8'),
      vectorJson({
        name: 'doctor-result',
        request: { operation: 'doctor', args: {} },
        result: doctor,
      }),
      'the doctor contract vector is regenerated byte-for-byte from the real owner projection',
    );
    store.database
      .prepare(
        `INSERT INTO activation_intents
         (id, kind, document, digest, effect, replacement_of_version, required_points, acquisition_scopes, status,
          created_at, updated_at, approval_id)
         VALUES ('activation-1', 'enable-all', '{"documentVersion":1,"kind":"enable-all","switchGeneration":1,"ruleVersions":[]}', 'digest-1', '{}', NULL,
                 '[]', '[]', 'pending', 1, 1, 'approval-1')`,
      )
      .run();
    const owner = createOwnerB3ControlService({
      store,
      ports: {
        quiescer: new WriterQuiescer(),
        secrets: {
          async targetSecretCreate() {
            secretCalls += 1;
            return { kind: 'target-secret', targetId: 'target-1', version: 1, generation: 1 };
          },
        } as never,
        assertObjectSecretReady: async () => ({ ready: true as const }),
      },
      // No account is connected: these vectors exercise error codes, and resume's live-account fence refuses first.
      config: { load: async () => emptyConfig() },
      activations: { issueApprovalViewChallenge: async () => approvalChallenge },
      cipher: { encrypt: async () => Buffer.alloc(0) },
      now: () => 1_000,
    });
    const errorCode = async (work: () => Promise<unknown>): Promise<string> => {
      try {
        await work();
        assert.fail('the real operation must fail for this stable error vector');
      } catch (error) {
        // The owner maps a B3 domain refusal to BAD_DATA at its control boundary; the other operations already use
        // their stable CommsError codes. Both paths are the production owner operations exercised below.
        if (error instanceof EventDomainError) return 'BAD_DATA';
        if (error instanceof CommsError) return error.code;
        throw error;
      }
    };
    const operator = new B3OperatorControl({
      store,
      ports: { quiescer: new WriterQuiescer(), closeSubscriberStreams: () => undefined },
    } as never);
    const errorVectors = [
      {
        name: 'error-usage',
        request: {
          operation: 'targetUrlSet',
          args: { targetId: 'target-1', newVersion: 1 },
          origin: 'interactive-terminal',
        },
        error: {
          code: await errorCode(() =>
            owner.handle({
              operation: 'targetUrlSet',
              args: { targetId: 'target-1', newVersion: 1 },
              origin: 'interactive-terminal',
            }),
          ),
        },
      },
      {
        name: 'error-bad-data',
        request: {
          operation: 'ruleTest',
          args: {
            document: INVALID_RULE_DOCUMENT,
            catalogue: { type: 'gmail.message.received', version: 1, exampleIndex: 0 },
          },
        },
        error: {
          code: await errorCode(() =>
            owner.handle({
              operation: 'ruleTest',
              args: {
                document: INVALID_RULE_DOCUMENT,
                catalogue: { type: 'gmail.message.received', version: 1, exampleIndex: 0 },
              },
            }),
          ),
        },
      },
      {
        name: 'error-approval-void',
        request: { operation: 'targetTest', args: { targetId: 'target-1', targetVersion: 1 } },
        error: {
          code: await errorCode(() =>
            owner.handle({ operation: 'targetTest', args: { targetId: 'target-1', targetVersion: 1 } }),
          ),
        },
      },
      {
        name: 'error-not-found',
        request: { operation: 'removeSubscriber', args: { subscriberId: 'subscriber-1' } },
        error: {
          code: await errorCode(() =>
            operator.handle({ operation: 'removeSubscriber', args: { subscriberId: 'subscriber-1' } }),
          ),
        },
      },
      {
        name: 'error-config',
        request: {
          operation: 'ruleTestRetained',
          args: { eventId: 'event-1', ruleId: 'rule-1', ruleVersion: 1 },
        },
        error: {
          code: await errorCode(() =>
            owner.handle({
              operation: 'ruleTestRetained',
              args: { eventId: 'event-1', ruleId: 'rule-1', ruleVersion: 1 },
            }),
          ),
        },
      },
    ];
    assert.deepEqual(
      errorVectors.map((vector) => vector.error.code),
      B3_CONTROL_ERROR_CODES,
      'every stable desktop-visible error code is produced by a real owner operation over repository fakes',
    );
    assert.deepEqual(errorVectors, [
      vector('error-usage'),
      vector('error-bad-data'),
      vector('error-approval-void'),
      vector('error-not-found'),
      vector('error-config'),
    ]);
    assert.equal(
      await readFile(join(FIXTURES, 'error-vectors.json'), 'utf8'),
      vectorJson(errorVectors),
      'stable error vectors are regenerated byte-for-byte from real owner operations',
    );
    const ready = await owner.handle(request('approval-view-ready') as never);
    assert.deepEqual(ready, vector('approval-view-ready').result);
    store.database.prepare("UPDATE activation_intents SET status = 'completed' WHERE id = 'activation-1'").run();
    const stale = await owner.handle(request('approval-view-stale') as never);
    assert.deepEqual(
      stale,
      vector('approval-view-stale').result,
      'the checked-in stale result is generated by the real owner operation',
    );
    store.database.prepare("UPDATE activation_intents SET status = 'pending' WHERE id = 'activation-1'").run();
    const digestMismatch = await owner.handle(request('approval-view-digest-mismatch') as never);
    assert.deepEqual(
      digestMismatch,
      vector('approval-view-digest-mismatch').result,
      'the checked-in digest-drift result is generated by the real owner operation',
    );
    approvalChallenge = null;
    const challengeExpired = await owner.handle(request('approval-view-challenge-expired') as never);
    assert.deepEqual(
      challengeExpired,
      vector('approval-view-challenge-expired').result,
      'the checked-in expired-challenge result is generated by the real owner operation',
    );
    assert.equal(
      await readFile(join(FIXTURES, 'approval-view-ready.json'), 'utf8'),
      `${JSON.stringify(
        {
          name: 'approval-view-ready',
          request: { operation: 'approvalView', args: { approvalId: 'approval-1', digest: 'digest-1' } },
          result: ready,
        },
        null,
        2,
      )}\n`,
      'the ready contract vector is regenerated byte-for-byte from the real owner result',
    );
    assert.equal(
      await readFile(join(FIXTURES, 'approval-view-variants.json'), 'utf8'),
      `${JSON.stringify(
        [
          {
            name: 'approval-view-stale',
            request: { operation: 'approvalView', args: { approvalId: 'approval-1', digest: 'digest-1' } },
            result: stale,
          },
          {
            name: 'approval-view-digest-mismatch',
            request: { operation: 'approvalView', args: { approvalId: 'approval-1', digest: 'wrong' } },
            result: digestMismatch,
          },
          {
            name: 'approval-view-challenge-expired',
            request: { operation: 'approvalView', args: { approvalId: 'approval-1', digest: 'digest-1' } },
            result: challengeExpired,
          },
        ],
        null,
        2,
      )}\n`,
      'the stale, digest and challenge contract vectors are regenerated byte-for-byte from real owner results',
    );
    const judgeE = await owner.handle(request('judge-e-unavailable') as never);
    assert.deepEqual(judgeE, vector('judge-e-unavailable').result);
    await assertVectorFile('unavailable.json', {
      name: 'judge-e-unavailable',
      request: request('judge-e-unavailable'),
      result: judgeE,
    });
    const judgeE2 = await owner.handle(request('judge-e2-unavailable') as never);
    assert.deepEqual(judgeE2, vector('judge-e2-unavailable').result);
    await assertVectorFile('unavailable-e2.json', {
      name: 'judge-e2-unavailable',
      request: request('judge-e2-unavailable'),
      result: judgeE2,
    });
    const held = await owner.handle(request('held-list-empty') as never);
    assert.deepEqual(held, vector('held-list-empty').result);
    await assertVectorFile('holds.json', {
      name: 'held-list-empty',
      request: request('held-list-empty'),
      result: held,
    });
    const heldDecide = await owner.handle(request('held-decide-unavailable') as never);
    assert.deepEqual(heldDecide, vector('held-decide-unavailable').result);
    await assertVectorFile('held-decide.json', {
      name: 'held-decide-unavailable',
      request: request('held-decide-unavailable'),
      result: heldDecide,
    });
    const appSecretUnavailable = await owner.handle(request('secret-app-unavailable') as never);
    assert.deepEqual(appSecretUnavailable, vector('secret-app-unavailable').result);
    await assertVectorFile('secret-origin.json', {
      name: 'secret-app-unavailable',
      request: request('secret-app-unavailable'),
      result: appSecretUnavailable,
    });
    assert.deepEqual(
      await owner.handle({ ...request('secret-app-unavailable'), origin: 'forged-window' } as never),
      vector('secret-app-unavailable').result,
    );
    assert.equal(secretCalls, 0, 'an app/window label is refused before the secret operation');
    assert.deepEqual(
      await owner.handle({ ...request('secret-app-unavailable'), origin: 'interactive-terminal' } as never),
      { kind: 'target-secret', targetId: 'target-1', version: 1, generation: 1 },
      'only the interactive terminal origin reaches the real secret operation seam',
    );
    assert.equal(secretCalls, 1);

    const generatedB3OperationResults = await Promise.all(
      [
        'judge-add-result',
        'judge-update-result',
        'judge-remove-result',
        'judge-test-result',
        'budget-show-result',
        'budget-update-result',
        'judge-kinds-list-result',
        'judge-kind-enable-result',
        'judge-kind-disable-result',
        'judge-model-remove-result',
        'target-secret-rotate-result',
        'target-url-set-result',
        'subscriber-token-create-result',
        'subscriber-token-rotate-result',
        'judge-key-set-result',
        'judge-key-rotate-result',
        'secrets-migrate-result',
      ].map(async (name) => {
        const checked = vector(name);
        return { ...checked, result: await owner.handle(checked.request as never) };
      }),
    );
    assert.deepEqual(
      generatedB3OperationResults,
      [
        vector('judge-add-result'),
        vector('judge-update-result'),
        vector('judge-remove-result'),
        vector('judge-test-result'),
        vector('budget-show-result'),
        vector('budget-update-result'),
        vector('judge-kinds-list-result'),
        vector('judge-kind-enable-result'),
        vector('judge-kind-disable-result'),
        vector('judge-model-remove-result'),
        vector('target-secret-rotate-result'),
        vector('target-url-set-result'),
        vector('subscriber-token-create-result'),
        vector('subscriber-token-rotate-result'),
        vector('judge-key-set-result'),
        vector('judge-key-rotate-result'),
        vector('secrets-migrate-result'),
      ],
      'every pre-E or app-origin B3 result vector is produced by the real owner service',
    );
    assert.equal(
      await readFile(join(FIXTURES, 'b3-operation-results.json'), 'utf8'),
      vectorJson(generatedB3OperationResults),
      'the complete pre-E and app-origin B3 result fixture is regenerated byte-for-byte from the real owner service',
    );

    const ordinary = vector('target-test-active-request');
    assert.deepEqual(
      Object.keys((ordinary.request as { args: Record<string, unknown> }).args).sort(),
      ['targetId', 'targetVersion'],
      'the pending selector exists only in approval-flow vectors, never an ordinary CLI/MCP request',
    );
    assert.equal(
      (vector('pending-target-approval-flow').request as { surface: string }).surface,
      'app-approval-screen',
    );
    assert.match(B3_CONTROL_V1_SUCCESSOR_REQUIREMENT, /E imports its real code and this contract/u);
    assert.match(B3_CONTROL_V1_SUCCESSOR_REQUIREMENT, /before any owner registration or callable judge/u);
    assert.match(B3_CONTROL_V1_SUCCESSOR_REQUIREMENT, /requires B3 merged/u);

    const source = await readFile(join(import.meta.dirname, '../src/operations/b3-contract.ts'), 'utf8');
    assert.doesNotMatch(source, /from ['"][^'"]*(?:desktop|judge-runtime)[^'"]*['"]/u);
    assert.doesNotMatch(
      source,
      /terminalReveal|HumanSecret|hiddenUrl/u,
      'the data-only contract exports no secret value or type',
    );
  } finally {
    store.close();
    await rm(stateDir, { recursive: true, force: true });
  }
});
