#!/usr/bin/env node
/**
 * Writes core's snapshot of the channel manifests, `packages/core/src/channels.generated.ts`, from the `"agentcomms"`
 * field of every channel's `package.json` — and checks every manifest against core's schema on the way.
 *
 * Core cannot read a channel's `package.json` when it runs: the Gmail package is not installed beside the core server
 * that registers it. So what core knows about each channel is built in, as a snapshot taken here, and `--check` fails
 * the build when the snapshot and the manifests disagree — the same arrangement as the reference pages
 * (`sync-reference.mjs`).
 *
 *   node --experimental-strip-types scripts/sync-channels.mjs           # write the snapshot
 *   node --experimental-strip-types scripts/sync-channels.mjs --check   # fail if it is out of date
 */
import { execFileSync } from 'node:child_process';
import { realpathSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { ROOT, readChannels, readDeclarations } from './channels.mjs';

export const SNAPSHOT = join('packages', 'core', 'src', 'channels.generated.ts');

/** The snapshot's source for the channels under `root`: validated, then formatted as the formatter would. */
export async function snapshotSource(root = ROOT) {
  const { parseChannelEntries } = await import(pathToFileURL(join(ROOT, 'packages/core/src/channel-manifest.ts')).href);
  // Keep the channel snapshot on the registry's channel view; declared services use the broader declaration view.
  const channels = readChannels(root);
  const { services } = readDeclarations(root);
  const entries = parseChannelEntries(channels.map(({ packageName, manifest }) => ({ packageName, manifest })));
  const serviceEntries = services.map(({ packageName, declaration }) => ({ packageName, declaration }));
  const serverNames = [
    ...entries.map((entry) => entry.manifest.channel),
    ...serviceEntries.map((entry) => entry.declaration.server.defaultName),
  ];
  const duplicate = serverNames.find((name, index) => serverNames.indexOf(name) !== index);
  if (duplicate !== undefined) throw new Error(`two declared MCP servers use the name ${JSON.stringify(duplicate)}`);
  const source = [
    '/*',
    ' * Generated by scripts/sync-channels.mjs from the channel and service declarations in package.json.',
    ' * Run `pnpm sync:channels` after changing one; do not edit this file.',
    ' */',
    "import type { ChannelEntry } from './channel-manifest.ts';",
    "import type { ServiceEntry } from './service-manifest.ts';",
    '',
    '/** The channels built into this release, by their word: a channel is a string, and these are the known ones. */',
    `export type BuiltInChannel = ${entries.map((entry) => JSON.stringify(entry.manifest.channel)).join(' | ')};`,
    '',
    '/** Every first-party channel, the core first: what core knows about each without installing it. */',
    `export const CHANNEL_SNAPSHOT: readonly ChannelEntry[] = ${JSON.stringify(entries, null, 2)};`,
    '',
    '/** Every declared service server: what core knows about it without installing it. */',
    `export const SERVICE_SNAPSHOT: readonly ServiceEntry[] = ${JSON.stringify(serviceEntries, null, 2)};`,
    '',
  ].join('\n');
  // Through the repository's own formatter, so `biome ci` and this script agree about every byte.
  return execFileSync(
    process.execPath,
    [join(ROOT, 'node_modules', '@biomejs', 'biome', 'bin', 'biome'), 'format', `--stdin-file-path=${SNAPSHOT}`],
    { cwd: ROOT, input: source, encoding: 'utf8' },
  );
}

const check = process.argv.includes('--check');
// Compared through realpath, as `packages.mjs` does: a temp directory can be a symlink (macOS `/tmp`).
const invoked = process.argv[1] ? realpathSync(process.argv[1]) : '';
if (invoked === realpathSync(fileURLToPath(import.meta.url))) {
  const path = join(ROOT, SNAPSHOT);
  const wanted = await snapshotSource();
  const current = await readFile(path, 'utf8').catch(() => null);
  if (check) {
    if (current !== wanted) {
      console.error(
        `out of date: ${SNAPSHOT.split('\\').join('/')}\n\nRun \`pnpm sync:channels\` and commit the result.`,
      );
      process.exit(1);
    }
    console.log('the channel snapshot is in step with the manifests.');
  } else {
    if (current !== wanted) await writeFile(path, wanted);
    console.log(
      `server snapshot written: ${[...readDeclarations().channels, ...readDeclarations().services]
        .map((entry) => entry.directory)
        .join(', ')}.`,
    );
  }
}
